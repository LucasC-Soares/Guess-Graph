export type TranslationKey = keyof typeof messages.pt;

export function translate(locale: Locale, key: TranslationKey): string {
  return messages[locale][key];
}

const questionTranslationKeys: Record<QuestionType, TranslationKey> = {
  [QuestionType.IS_CONNECTED]: 'questionIsConnected',
  [QuestionType.IS_BIPARTITE]: 'questionIsBipartite',
  [QuestionType.HAS_CYCLE]: 'questionHasCycle',
  [QuestionType.IS_TREE]: 'questionIsTree',
  [QuestionType.HAS_BRIDGE]: 'questionHasBridge',
  [QuestionType.MAX_DEGREE_GREATER_THAN]: 'questionMaxDegreeGreaterThan',
};

export function translateQuestion(
  locale: Locale,
  type: QuestionType,
  threshold?: number,
): string {
  return translate(locale, questionTranslationKeys[type]).replace(
    '{threshold}',
    String(threshold ?? 'X'),
  );
}
